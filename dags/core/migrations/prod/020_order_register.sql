CREATE INDEX idx_orders_retail_snapshot_at ON public.orders (retail_snapshot_at) WHERE retail_snapshot_at IS NOT NULL;
CREATE INDEX idx_orders_retail_updated_at  ON public.orders (retail_updated_at)  WHERE retail_updated_at  IS NOT NULL;

CREATE TABLE public.order_positions (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id               bigint,                        -- → orders.id (post_load по recorder+recorder_type)
    -- технические ключи
    recorder               uuid        NOT NULL,          -- _Document271_IDRRef
    recorder_type          integer     NOT NULL,          -- 271
    vt_kind                varchar(10) NOT NULL,          -- 'product' (_VT4708 Товары) | 'service' (_VT4746 Услуги)
    line_no                integer     NOT NULL,          -- _LineNo4709 | _LineNo4747
    -- DIM refs
    nomenklatura_id        bigint,                        -- _Fld4714RRef | _Fld4754RRef → dim_nomenklatura
    kachestvo_id           bigint,                        -- _Fld24518RRef (только товары) → dim_kachestvo
    otvetstvennyy_id       bigint,                        -- _Fld24668RRef | _Fld24669RRef → dim_otvetstvennyy
