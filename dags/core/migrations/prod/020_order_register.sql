    podrazdelenie_id       bigint,                        -- Подразделение   _Fld4697RRef → dim_podrazdelenie
    sklad_id               bigint,                        -- СкладГруппа     _Fld4699_RRRef (только тип 169) → dim_sklad
    gruzopoluchatel_id     bigint,                        -- Грузополучатель _Fld4677RRef → dim_kontragent
    -- меры / атрибуты
