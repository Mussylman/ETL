    -- меры
    kolichestvo            numeric(18,4),                 -- _Fld4711 | _Fld4749
    tsena                  numeric(18,4),                 -- _Fld4724 | _Fld4750
    summa                  numeric(18,4),                 -- _Fld4720 | _Fld4751
    nds                    numeric(18,4),                 -- _Fld4721 | _Fld4753
    skidka_pct             numeric(18,4),                 -- ПроцентСкидкиНаценки _Fld4716 | _Fld4755
    podarochnaya_skidka    numeric(18,4),                 -- ПодарочнаяСкидка _Fld19986 (только товары)
