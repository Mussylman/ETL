CREATE INDEX idx_order_positions_order_id        ON public.order_positions (order_id);
CREATE INDEX idx_order_positions_nomenklatura_id ON public.order_positions (nomenklatura_id);
CREATE INDEX idx_order_positions_sklad_id        ON public.order_positions (sklad_id);
CREATE INDEX idx_order_positions_etl_updated_at  ON public.order_positions (etl_updated_at);

COMMIT;

