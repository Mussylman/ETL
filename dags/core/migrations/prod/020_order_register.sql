    raw_refs               jsonb,
    etl_loaded_at          timestamp DEFAULT now(),
    etl_updated_at         timestamp,
    retail_snapshot_at     timestamp,
    retail_updated_at      timestamp,
    CONSTRAINT order_positions_nk_key UNIQUE (recorder, recorder_type, vt_kind, line_no)
