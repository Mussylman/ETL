"""
Соединение с PostgreSQL — только явно.

Значения по умолчанию у conn_id нет ни в библиотеке, ни в CLI: молчаливое умолчание
означало бы, что ручной запуск без --pg-conn пишет в базу, которую никто не выбирал, а
умолчание etl_prod — что он пишет в PROD. Поэтому пропущенное соединение — немедленная
ошибка до открытия соединения и любых изменений.
"""


def require_conn(name: str, value):
    if not value:
        raise ValueError(f"{name} не задан: соединение с PostgreSQL указывается явно "
                         f"(значения по умолчанию нет), например {name}='etl_prod'")
    return value
