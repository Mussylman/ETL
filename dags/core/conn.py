"""
Соединение с PostgreSQL — только явно.

Значения по умолчанию у conn_id нет ни в библиотеке, ни в CLI: раньше молчаливым
умолчанием была TEST-база postgre_test_base, и ручной запуск без --pg-conn писал бы в неё.
Замена умолчания на etl_prod была бы ещё опаснее. Поэтому пропущенное соединение —
немедленная ошибка до открытия соединения и любых изменений.
"""


def require_conn(name: str, value):
    if not value:
        raise ValueError(f"{name} не задан: соединение с PostgreSQL указывается явно "
                         f"(значения по умолчанию нет), например {name}='etl_prod'")
    return value
